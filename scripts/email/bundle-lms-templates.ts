/**
 * Bundle backend/src/email/lms/<alias>.html + <alias>.json into
 * backend/src/email/lms/lmsTemplatesBundle.ts (the runtime cannot read these files).
 * Re-run after editing an LMS template (a test checks the bundle matches the files):
 *   npx tsx scripts/email/bundle-lms-templates.ts
 * LMS templates are separate from templates/ (not in TEMPLATE_REGISTRY, not pushed to
 * Resend) and are sent only by sendLmsTemplate, behind LMS_EMAILS_ENABLED.
 */
import fs from 'node:fs';
import path from 'node:path';

export const LMS_TEMPLATES_DIR = path.resolve(__dirname, '../../backend/src/email/lms');
export const LMS_BUNDLE_PATH = path.join(LMS_TEMPLATES_DIR, 'lmsTemplatesBundle.ts');

export function buildLmsBundleSource(): string {
  const aliases = fs.readdirSync(LMS_TEMPLATES_DIR).filter((f) => f.endsWith('.html')).map((f) => f.replace(/\.html$/, '')).sort();
  const entries = aliases.map((alias) => {
    const html = fs.readFileSync(path.join(LMS_TEMPLATES_DIR, `${alias}.html`), 'utf8');
    const meta = JSON.parse(fs.readFileSync(path.join(LMS_TEMPLATES_DIR, `${alias}.json`), 'utf8')) as { subject?: string; variables?: { key: string; fallback_value?: unknown }[] };
    const variables = (meta.variables ?? []).map((v) => v.key);
    const fallbacks = Object.fromEntries(
      (meta.variables ?? []).filter((v) => v.fallback_value !== null && v.fallback_value !== undefined).map((v) => [v.key, String(v.fallback_value)]),
    );
    return `  ${JSON.stringify(alias)}: {\n    subject: ${JSON.stringify(meta.subject ?? '')},\n    variables: ${JSON.stringify(variables)},\n    fallbacks: ${JSON.stringify(fallbacks)},\n    html: ${JSON.stringify(html)},\n  },`;
  });
  return [
    '// GENERATED by scripts/email/bundle-lms-templates.ts from src/email/lms/*.{html,json}. Do not edit.',
    '// Re-run `npx tsx scripts/email/bundle-lms-templates.ts` (repo root) after editing an LMS template.',
    '',
    'export interface BundledLmsTemplate {',
    '  subject: string;',
    '  /** Every variable the template uses (all required by sendLmsTemplate). */',
    '  variables: readonly string[];',
    '  /** fallback_value per variable key, from <alias>.json */',
    '  fallbacks: Readonly<Record<string, string>>;',
    '  html: string;',
    '}',
    '',
    'export const LMS_TEMPLATES_BUNDLE = {',
    ...entries,
    '} as const satisfies Record<string, BundledLmsTemplate>;',
    '',
    'export type LmsTemplateAlias = keyof typeof LMS_TEMPLATES_BUNDLE;',
    '',
  ].join('\n');
}

if (require.main === module) {
  fs.writeFileSync(LMS_BUNDLE_PATH, buildLmsBundleSource());
  console.log(`Wrote ${path.relative(process.cwd(), LMS_BUNDLE_PATH)}`);
}
