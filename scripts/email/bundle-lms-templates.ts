/**
 * Bundle the code-sent (not Resend-hosted) email templates into TypeScript the
 * runtime can import (Vercel functions cannot read these files):
 *   backend/src/email/lms/<alias>-<lang>.html + .json     -> lms/lmsTemplatesBundle.ts
 *   backend/src/email/parents/<alias>-<lang>.html + .json -> parents/parentTemplatesBundle.ts
 * Re-run after editing one of them (a test checks each bundle matches its files):
 *   npx tsx scripts/email/bundle-lms-templates.ts
 * Only `subject` and `variables[].key` / `fallback_value` are bundled; the other
 * fields of <alias>-<lang>.json (status, number, recipient, trigger, delivery,
 * frequency, samples, preview variants) are catalogue metadata for people and
 * for scripts/email/render-previews.mjs.
 * These templates are separate from templates/ (not in TEMPLATE_REGISTRY, not
 * pushed to Resend): LMS ones are sent only by sendLmsTemplate (behind
 * LMS_EMAILS_ENABLED), parent ones only by sendParentTemplate.
 */
import fs from 'node:fs';
import path from 'node:path';

const EMAIL_DIR = path.resolve(__dirname, '../../backend/src/email');

export interface CodeTemplateSet {
  /** Folder holding <alias>.html + <alias>.json (and the bundle). */
  dir: string;
  bundlePath: string;
  /** Prefix of the generated names: Lms -> BundledLmsTemplate, LMS_TEMPLATES_BUNDLE, LmsTemplateAlias. */
  typePrefix: string;
  constPrefix: string;
  /** The sender that uses this bundle (for the generated doc comment). */
  sender: string;
}

export const LMS_TEMPLATES_DIR = path.join(EMAIL_DIR, 'lms');
export const LMS_BUNDLE_PATH = path.join(LMS_TEMPLATES_DIR, 'lmsTemplatesBundle.ts');
export const PARENT_TEMPLATES_DIR = path.join(EMAIL_DIR, 'parents');
export const PARENT_BUNDLE_PATH = path.join(PARENT_TEMPLATES_DIR, 'parentTemplatesBundle.ts');

export const LMS_TEMPLATE_SET: CodeTemplateSet = { dir: LMS_TEMPLATES_DIR, bundlePath: LMS_BUNDLE_PATH, typePrefix: 'Lms', constPrefix: 'LMS', sender: 'sendLmsTemplate' };
export const PARENT_TEMPLATE_SET: CodeTemplateSet = { dir: PARENT_TEMPLATES_DIR, bundlePath: PARENT_BUNDLE_PATH, typePrefix: 'Parent', constPrefix: 'PARENT', sender: 'sendParentTemplate' };

export function buildBundleSourceFor(set: CodeTemplateSet): string {
  const folder = path.basename(set.dir);
  const aliases = fs.readdirSync(set.dir).filter((f) => f.endsWith('.html')).map((f) => f.replace(/\.html$/, '')).sort();
  const entries = aliases.map((alias) => {
    const html = fs.readFileSync(path.join(set.dir, `${alias}.html`), 'utf8');
    const meta = JSON.parse(fs.readFileSync(path.join(set.dir, `${alias}.json`), 'utf8')) as { subject?: string; variables?: { key: string; fallback_value?: unknown }[] };
    const variables = (meta.variables ?? []).map((v) => v.key);
    const fallbacks = Object.fromEntries(
      (meta.variables ?? []).filter((v) => v.fallback_value !== null && v.fallback_value !== undefined).map((v) => [v.key, String(v.fallback_value)]),
    );
    return `  ${JSON.stringify(alias)}: {\n    subject: ${JSON.stringify(meta.subject ?? '')},\n    variables: ${JSON.stringify(variables)},\n    fallbacks: ${JSON.stringify(fallbacks)},\n    html: ${JSON.stringify(html)},\n  },`;
  });
  const label = set.typePrefix === 'Lms' ? 'an LMS' : `a ${set.typePrefix.toLowerCase()}`;
  return [
    `// GENERATED by scripts/email/bundle-lms-templates.ts from src/email/${folder}/*.{html,json}. Do not edit.`,
    `// Re-run \`npx tsx scripts/email/bundle-lms-templates.ts\` (repo root) after editing ${label} template.`,
    '',
    `export interface Bundled${set.typePrefix}Template {`,
    '  subject: string;',
    `  /** Every variable the template uses (all required by ${set.sender}). */`,
    '  variables: readonly string[];',
    '  /** fallback_value per variable key, from <alias>.json */',
    '  fallbacks: Readonly<Record<string, string>>;',
    '  html: string;',
    '}',
    '',
    `export const ${set.constPrefix}_TEMPLATES_BUNDLE = {`,
    ...entries,
    `} as const satisfies Record<string, Bundled${set.typePrefix}Template>;`,
    '',
    `export type ${set.typePrefix}TemplateAlias = keyof typeof ${set.constPrefix}_TEMPLATES_BUNDLE;`,
    '',
  ].join('\n');
}

export function buildLmsBundleSource(): string {
  return buildBundleSourceFor(LMS_TEMPLATE_SET);
}

export function buildParentBundleSource(): string {
  return buildBundleSourceFor(PARENT_TEMPLATE_SET);
}

if (require.main === module) {
  for (const set of [LMS_TEMPLATE_SET, PARENT_TEMPLATE_SET]) {
    fs.writeFileSync(set.bundlePath, buildBundleSourceFor(set));
    console.log(`Wrote ${path.relative(process.cwd(), set.bundlePath)}`);
  }
}
