/**
 * Bundle templates/<alias>.html + <alias>.json into backend/src/email/templatesBundle.ts so the
 * runtime (Vercel functions cannot read these files) can render them. Re-run after editing a template:
 *   npx tsx scripts/email/bundle-templates.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { TEMPLATE_ALIASES } from '../../backend/src/email/templateRegistry';
import { TEMPLATES_DIR, type TemplateMeta } from './common';

export const BUNDLE_PATH = path.resolve(TEMPLATES_DIR, '../templatesBundle.ts');

export function buildBundleSource(): string {
  const entries = TEMPLATE_ALIASES.map((alias) => {
    const html = fs.readFileSync(path.join(TEMPLATES_DIR, `${alias}.html`), 'utf8');
    const meta = JSON.parse(fs.readFileSync(path.join(TEMPLATES_DIR, `${alias}.json`), 'utf8')) as TemplateMeta;
    const fallbacks = Object.fromEntries(
      (meta.variables ?? []).filter((v) => v.fallback_value !== null && v.fallback_value !== undefined).map((v) => [v.key, String(v.fallback_value)]),
    );
    return `  ${JSON.stringify(alias)}: {\n    subject: ${JSON.stringify(meta.subject ?? '')},\n    fallbacks: ${JSON.stringify(fallbacks)},\n    html: ${JSON.stringify(html)},\n  },`;
  });
  return [
    '// GENERATED by scripts/email/bundle-templates.ts from src/email/templates/*.{html,json}. Do not edit.',
    '// Re-run `npx tsx scripts/email/bundle-templates.ts` (repo root) after editing a template.',
    "import type { TemplateAlias } from './templateRegistry';",
    '',
    'export interface BundledTemplate {',
    '  subject: string;',
    '  /** fallback_value per variable key, from <alias>.json */',
    '  fallbacks: Readonly<Record<string, string>>;',
    '  html: string;',
    '}',
    '',
    'export const TEMPLATES_BUNDLE: Record<TemplateAlias, BundledTemplate> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

if (require.main === module) {
  fs.writeFileSync(BUNDLE_PATH, buildBundleSource());
  console.log(`Wrote ${path.relative(process.cwd(), BUNDLE_PATH)} (${TEMPLATE_ALIASES.length} templates)`);
}
