// Writes docs/lms/SEED_USERS.md: every account in the lms-test full data set (role, state, school, email), grouped by role.
// No password: every account signs in with the one password the owner set in Vercel (SEED_USER_PASSWORD), never written anywhere.
// Usage (from backend/): npx tsx src/scripts/fullSeedSheet.ts
// Names, emails and states come from the fixed plan, so they are the same whatever day this runs (only dates move).
import { writeFileSync } from 'fs';
import path from 'path';
import { type SeedCode, buildPlan, SEED_BATCH, type SeedUser } from '../maintenance/fullSeed/plan';
import { SCHOOLS } from '../maintenance/fullSeed/content';

export function sheet(users: SeedUser[]): string {
  const groups: [string, (u: SeedUser) => boolean][] = [
    ['Platform admin', (u) => u.role === 'enara-admin'],
    ['School admins', (u) => u.role === 'admin'],
    ['Academic managers', (u) => u.role === 'academic_manager'],
    ['Teachers', (u) => u.role === 'teacher'],
    ['Students', (u) => u.role === 'student'],
    ['Parents', (u) => u.role === 'parent'],
    ['Invitations (not accounts)', (u) => u.role.startsWith('invitation')],
    ['Parent link codes (not accounts; codes are not shown)', (u) => u.role === 'parent code'],
  ];
  const cell = (s: string) => s.replace(/\|/g, '\\|');
  const out: string[] = [
    '# lms-test accounts (full data set)',
    '',
    `Generated by \`backend/src/scripts/fullSeedSheet.ts\` (batch \`${SEED_BATCH}\`). lms-test only: these records are listed in the hidden \`seed_registry\` and are never copied to test.enara.app or production (GO_LIVE_CHECKLIST.md).`,
    '',
    '- **Password:** every account uses the one password set in Vercel as `SEED_USER_PASSWORD`. It is not in this file or anywhere in the repo.',
    '- **Load / remove / count:** `POST /api/maintenance/full-seed` with `{"action":"run"}`, `{"action":"remove"}` or `{"action":"status"}` (maintenance token).',
    '- **Email:** all addresses are on `school.enara.app`, which has no mailboxes; lms-test also redirects all mail.',
    '',
    '## Schools',
    '',
    '| School | Status | Parent portal | Results to parents | Notes |',
    '|---|---|---|---|---|',
    ...SCHOOLS.map((s) => `| ${s.name} | ${s.status} | ${s.portal === 'off' ? 'off' : 'on'} | ${s.results === 'immediately' ? 'immediately' : 'after release'} | ${cell(s.onboarding)} |`),
    '',
  ];
  for (const [title, f] of groups) {
    const rows = users.filter(f);
    if (!rows.length) continue;
    out.push(`## ${title} (${rows.length})`, '', '| State | School | Email / name |', '|---|---|---|');
    for (const u of rows) out.push(`| ${cell(u.state)} | ${cell(u.school ?? '—')} | ${u.email ? `${u.email} (${cell(u.name)})` : cell(u.name)} |`);
    out.push('');
  }
  return out.join('\n');
}

/** The parent link codes, one row per student: what a parent types to link to that child. */
export function codeSheet(codes: SeedCode[]): string {
  const cell = (s: string) => s.replace(/\|/g, '\\|');
  const out = [
    '# lms-test parent link codes',
    '',
    'A parent types the code in the parent portal (Link a child) to link to that student. Each valid code works once and is valid for 30 days',
    'from the last data run. Parents who are already linked sign in with their email and the shared password, or with an email code.',
    '',
  ];
  for (const school of [...new Set(codes.map((c) => c.school))]) {
    const rows = codes.filter((c) => c.school === school);
    out.push(`## ${school} (${rows.length})`, '', '| Code | State | Student | Student email | Class | Parents already linked |', '|---|---|---|---|---|---|');
    for (const c of rows) out.push(`| \`${c.code}\` | ${c.state} | ${cell(c.studentName)} | ${c.studentEmail} | ${cell(c.className)} | ${c.parents.length ? c.parents.join(', ') : 'none yet'} |`);
    out.push('');
  }
  return out.join('\n');
}

if (require.main === module) {
  const plan = buildPlan(new Date());
  const file = path.join(__dirname, '../../../docs/lms/SEED_USERS.md');
  writeFileSync(file, sheet(plan.users));
  const codesFile = path.join(__dirname, '../../../docs/lms/PARENT_CODES.md');
  writeFileSync(codesFile, codeSheet(plan.codes));
  console.log(`wrote ${file} and ${codesFile}`);
}
